import * as esbuild from 'esbuild';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

// CLI for the SQLite -> Postgres importer: `node dist/import-sqlite.js --from matchexec.db --database-url postgres://...`.
// `node:sqlite` is a Node builtin (platform: 'node' keeps `node:`-prefixed modules external); no native module is needed.
await esbuild.build({
  entryPoints: [join(__dirname, 'scripts/import-sqlite.ts')],
  bundle: true,
  platform: 'node',
  target: 'node26',
  format: 'cjs',
  outfile: join(__dirname, 'dist/import-sqlite.js'),
  external: [
    // Only reached by the PGlite test helper (dynamic import); never installed in the image
    '@electric-sql/pglite',
    'drizzle-orm/pglite',
    'drizzle-orm/pglite/*',
    'pg-native',
  ],
  treeShaking: true,
  minify: true,
  sourcemap: false,
  logLevel: 'info',
  // CJS bundles have no import.meta; some dependencies (node-cron's daemon path) read import.meta.url at load time.
  define: { 'import.meta.url': '__importMetaUrl' },
  banner: {
    js: '// Import-SQLite Bundle - Generated by esbuild\n// MatchExec Match Bot\n' + "const __importMetaUrl = require('url').pathToFileURL(__filename).href;\n",
  },
});

console.log('✓ import-sqlite bundled successfully');
