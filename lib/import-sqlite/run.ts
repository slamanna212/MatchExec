/**
 * The SQLite -> Postgres import (plan Stage 5). One Postgres transaction covers: truncate of the import tables, all rows,
 * uploads -> blobs, identity sequence resets, verification and the `system_status.imported_from_sqlite` marker. Progress is
 * written to system_status on a separate connection (`statusDb`) so the loading screen sees it while the transaction is open.
 * After COMMIT the legacy files are renamed (never deleted).
 */
import { getTableName, sql } from 'drizzle-orm';
import type { Db, Executor } from '../db';
import { getSystemStatus, setSystemStatus } from '../db/system-status';
import { checkLegacyConsistency } from './consistency';
import { applyPendingLegacyMigrations, makeSafetyCopy, openWorkingCopy, renameMigrated } from './legacy-db';
import { MAPPINGS } from './mappings';
import type { TableMapping } from './mapping';
import { buildPlan, type ImportPlan, type PlannedTable } from './plan';
import { preflightMessage, toStoredReport } from './report';
import { checkUploads, defaultUploadDirs, insertUploads, listUploads } from './uploads';
import { verifyImport } from './verify';
import { PreflightError, VerificationError, type ImportHooks, type ImportReport, type ProgressEvent } from './types';

export interface RunImportOptions {
  /** Postgres (Drizzle). In production a pool-backed instance, in tests PGlite. */
  db: Db;
  legacyPath: string;
  backupDir: string;
  /** Upload directories to import; default: public/uploads next to the app. */
  uploadsDirs?: string[];
  allowLossy?: boolean;
  /**
   * Executor for live progress rows. Must be a DIFFERENT connection than the import transaction (pool-backed `db` works;
   * single-connection PGlite cannot, so pass `null` there to skip live progress).
   */
  statusDb?: Executor | null;
  now?: Date;
  hooks?: ImportHooks;
  log?: (message: string) => void;
  mappings?: TableMapping[];
  legacyMigrationsDir?: string;
  /** Leave matchexec.db where it is after a successful import (tests / dry runs). */
  skipRename?: boolean;
}

export interface RunImportResult {
  report: ImportReport;
  renamedTo: string | null;
}

const BATCH_PARAMS = 30_000;

async function insertTable(tx: Executor, planned: PlannedTable): Promise<void> {
  const { rows, info } = planned;
  if (rows.length === 0) return;
  const batchSize = Math.max(1, Math.min(500, Math.floor(BATCH_PARAMS / info.columns.length)));
  for (let i = 0; i < rows.length; i += batchSize) {
    const batch = rows.slice(i, i + batchSize);
    try {
      // Identity columns are GENERATED BY DEFAULT (lib/db/schema), so explicit ids are accepted without OVERRIDING SYSTEM VALUE.
      await tx.insert(info.mapping.table).values(batch as never);
    } catch (e) {
      const cause = (e as { cause?: { detail?: string; message?: string } }).cause;
      const detail = cause?.detail ?? cause?.message ?? (e as Error).message;
      throw new Error(`Inserting into ${info.name} failed (rows ${i + 1}-${i + batch.length}, first id ${String(batch[0][info.pk[0]] ?? '?')}): ${detail}`, { cause: e });
    }
  }
}

async function identityColumns(tx: Executor): Promise<Array<{ table: string; column: string }>> {
  const res = await tx.execute(sql`SELECT table_name AS "table", column_name AS "column" FROM information_schema.columns WHERE table_schema = 'public' AND is_identity = 'YES'`);
  return (res as unknown as { rows: Array<{ table: string; column: string }> }).rows;
}

/** Plan 5.3 step 6: setval every identity sequence to max(id). */
export async function resetSequences(tx: Executor): Promise<number> {
  const cols = await identityColumns(tx);
  for (const { table, column } of cols) {
    const t = `"public"."${table}"`;
    await tx.execute(sql.raw(`SELECT setval(pg_get_serial_sequence('${t}', '${column}'), COALESCE((SELECT max("${column}") FROM ${t}), 1), (SELECT max("${column}") FROM ${t}) IS NOT NULL)`));
  }
  return cols.length;
}

export async function runImport(options: RunImportOptions): Promise<RunImportResult> {
  const { db, hooks } = options;
  const now = options.now ?? new Date();
  const allowLossy = options.allowLossy ?? false;
  const mappings = options.mappings ?? MAPPINGS;
  const log = options.log ?? ((m: string) => { if (!process.env.VITEST) console.log(`[import-sqlite] ${m}`); });
  const statusDb = options.statusDb === undefined ? db : options.statusDb;

  const report: ImportReport = {
    startedAt: now.toISOString(), source: options.legacyPath, lossy: allowLossy, legacyMigrationsApplied: [],
    tables: {}, blobs: { imported: 0, skipped: 0, bytes: 0 }, repairs: [], issues: [],
  };

  const progress = async (e: ProgressEvent): Promise<void> => {
    log(e.message);
    if (!statusDb) return;
    try {
      await setSystemStatus({ phase: 'importing', message: e.message, progress: Math.min(99, Math.round(e.percent)), report: { importing: { step: e.phase, table: e.table ?? null } } }, statusDb);
    } catch { /* the loading screen is best effort */ }
  };

  let work: ReturnType<typeof openWorkingCopy> | null = null;
  let committed = false;
  try {
    await progress({ phase: 'copy', message: 'Copying the legacy database to the backups directory...', percent: 2 });
    report.safetyCopy = makeSafetyCopy(options.legacyPath, options.backupDir, now);
    log(`safety copy: ${report.safetyCopy}`);
    work = openWorkingCopy(report.safetyCopy);

    await progress({ phase: 'prepare', message: 'Bringing the legacy database up to date...', percent: 6 });
    report.legacyMigrationsApplied = applyPendingLegacyMigrations(work.db, options.legacyMigrationsDir);
    if (report.legacyMigrationsApplied.length > 0) log(`applied ${report.legacyMigrationsApplied.length} legacy migration(s): ${report.legacyMigrationsApplied.join(', ')}`);

    await progress({ phase: 'prepare', message: 'Checking the legacy data (preflight)...', percent: 10 });
    const consistency = checkLegacyConsistency(work.db);
    const plan: ImportPlan = buildPlan({ db: work.db, mappings, hints: consistency.hints, allowLossy, now });
    report.issues = plan.issues;
    report.repairs = plan.repairs;
    report.coalesced = plan.coalesced;
    report.ignoredLegacyColumns = plan.unmappedLegacyColumns;
    for (const [table, cols] of Object.entries(plan.unmappedLegacyColumns)) log(`note: legacy column(s) not imported (no longer in the schema): ${table}.${cols.join(', ')}`);
    for (const issue of consistency.issues) {
      if (allowLossy) report.repairs.push({ rule: 'lossy_legacy_disagreement', table: issue.table, id: issue.id, column: issue.column, action: `${issue.detail}; ${issue.lossyAction}`, known: false });
      else report.issues.push(issue);
    }
    const uploads = checkUploads(listUploads(options.uploadsDirs ?? defaultUploadDirs(process.env, options.legacyPath)), allowLossy, report.issues, report.repairs);
    report.blobs.skipped = 0;
    for (const t of plan.tables) report.tables[t.info.name] = { source: t.sourceCount, imported: t.rows.length, skipped: t.sourceCount - t.rows.length };
    if (report.issues.length > 0) throw new PreflightError(report, preflightMessage(report.issues));
    for (const r of report.repairs) log(`repair [${r.known ? 'known' : 'lossy'}] ${r.rule} ${r.table}${r.id ? ` ${r.id}` : ''}: ${r.action}`);

    const total = plan.tables.length;
    await db.transaction(async (tx) => {
      await tx.execute(sql.raw(`TRUNCATE ${[...plan.tables.map((t) => `"${getTableName(t.info.mapping.table)}"`), '"blobs"'].join(', ')} RESTART IDENTITY CASCADE`));
      let i = 0;
      for (const planned of plan.tables) {
        i++;
        await progress({ phase: 'tables', table: planned.info.name, message: `Importing ${planned.info.name} (${i}/${total})...`, percent: 12 + (i / total) * 68 });
        await insertTable(tx, planned);
        await hooks?.afterTable?.(planned.info.name, tx);
      }
      await progress({ phase: 'uploads', message: `Importing ${uploads.length} uploaded file(s)...`, percent: 82 });
      const blobResult = await insertUploads(tx, uploads);
      report.blobs.imported = blobResult.imported;
      report.blobs.bytes = blobResult.bytes;

      await progress({ phase: 'sequences', message: 'Resetting sequences...', percent: 86 });
      await resetSequences(tx);

      await hooks?.beforeVerify?.(tx);
      await progress({ phase: 'verify', message: 'Verifying standings and results...', percent: 90 });
      report.verification = await verifyImport(tx, work!.db, plan, blobResult.imported);

      report.finishedAt = new Date().toISOString();
      await progress({ phase: 'commit', message: 'Committing...', percent: 95 });
      // LAST statement of the transaction: it locks the system_status row, so the separate progress connection must not write after it.
      await setSystemStatus({ phase: 'importing', message: 'Legacy data imported', progress: 96, importedFromSqlite: true, report: toStoredReport(report) }, tx);
    });
    committed = true;
    log(`import committed: ${Object.values(report.tables).reduce((n, t) => n + t.imported, 0)} rows, ${report.blobs.imported} upload(s), ${report.repairs.length} repair(s)`);
    await hooks?.afterCommit?.();

    const renamedTo = options.skipRename ? null : finishRename(options.legacyPath, now, log);
    return { report, renamedTo };
  } catch (e) {
    report.error = e instanceof Error ? e.message : String(e);
    if (e instanceof VerificationError) report.issues = [];
    log(`import FAILED: ${report.error.split('\n')[0]}`);
    // The transaction (if any) has rolled back; record the failure for the loading screen. Never mask the real error.
    // After COMMIT the data is safe and the marker is set (a retry only finishes the rename), so no error state is recorded.
    if (!committed) try {
      await setSystemStatus({ phase: 'error', message: `Legacy import failed: ${report.error.split('\n')[0].slice(0, 300)}`, progress: 0, report: toStoredReport(report) }, db);
    } catch { /* status is best effort */ }
    throw e;
  } finally {
    work?.close();
  }
}

/** Plan 5.5. A failed rename (read-only mount) must not fail the migration: the marker prevents a second import. */
export function finishRename(legacyPath: string, now: Date, log: (m: string) => void = () => undefined): string | null {
  try {
    const target = renameMigrated(legacyPath, now);
    log(`legacy database renamed to ${target}`);
    return target;
  } catch (e) {
    log(`WARNING: could not rename ${legacyPath}: ${(e as Error).message}. The data is imported; rename or remove the file manually.`);
    return null;
  }
}

export async function isImportMarked(ex: Executor): Promise<boolean> {
  try {
    return (await getSystemStatus(ex))?.imported_from_sqlite === true;
  } catch {
    return false;
  }
}
