import * as esbuild from 'esbuild';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

// The "migrate" service: Drizzle migrations + game data seeding. Runs from the repo/app root so that
// ./drizzle (SQL migrations) and ./data/games (seed data) resolve (override with MATCHEXEC_MIGRATIONS_DIR).
await esbuild.build({
  entryPoints: [join(__dirname, 'lib/db/migrate-cli.ts')],
  bundle: true,
  platform: 'node',
  target: 'node26',
  format: 'cjs',
  outfile: join(__dirname, 'dist/migrate.js'),
  external: [
    // Only reached by the PGlite test helper (dynamic import); never installed in the image
    '@electric-sql/pglite',
    'drizzle-orm/pglite',
    'drizzle-orm/pglite/*',
    // pg's optional native binding (it falls back to the pure JS client)
    'pg-native',
  ],
  treeShaking: true,
  minify: true,
  sourcemap: false,
  logLevel: 'info',
  banner: {
    js: '// Migrate Bundle - Generated by esbuild\n// MatchExec Match Bot\n',
  },
});

console.log('✓ Migrate bundled successfully');
