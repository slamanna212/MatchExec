import * as esbuild from 'esbuild';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

// The web server (Hono: /api/*, /uploads/*, static SPA from dist/client). `pg` is pure JS and is bundled.
await esbuild.build({
  entryPoints: [join(__dirname, 'src/server/index.ts')],
  bundle: true,
  platform: 'node',
  target: 'node26',
  format: 'cjs',
  outfile: join(__dirname, 'dist/server.js'),
  external: [
    // Only reached by the PGlite test helper (dynamic import in lib/db/migrate.ts); never installed in the image
    '@electric-sql/pglite',
    'drizzle-orm/pglite',
    'drizzle-orm/pglite/*',
    // pg's optional native binding (it falls back to the pure JS client)
    'pg-native',
  ],
  treeShaking: true,
  minify: true,
  sourcemap: false,
  logLevel: 'info',
  // CJS bundles have no import.meta; some dependencies (node-cron's daemon path) read import.meta.url at load time.
  define: { 'import.meta.url': '__importMetaUrl' },
  banner: {
    js: '// Server Bundle - Generated by esbuild\n// MatchExec Match Bot\n' + "const __importMetaUrl = require('url').pathToFileURL(__filename).href;\n",
  },
});

console.log('✓ Server bundled successfully');
